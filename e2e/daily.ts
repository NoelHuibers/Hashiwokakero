// Playing today's daily like a player, with its solution from the server's database: the page
// never gets it, and the solvers refuse today's daily.
import { DatabaseSync } from 'node:sqlite';

import { expect, type Page, test } from '@playwright/test';

import { addBridge, board, DAILY_KEY, missing, type Puzzle, saved } from './board';
import { DB_PATH, VISUAL_DB_PATH } from './env';

/** The database of the running test's server, see `VISUAL_URL`. */
const database = (options: { readOnly?: boolean } = {}) =>
  new DatabaseSync(test.info().project.name === 'visual' ? VISUAL_DB_PATH : DB_PATH, { ...options, timeout: 5_000 });

/** The solution of today's daily, once it was started (`get_or_create` in src/server/daily). */
export function dailySolution(puzzle: Puzzle): number[] {
  const db = database({ readOnly: true });
  try {
    const rows = db.prepare('SELECT puzzle, solution FROM dailies ORDER BY day DESC').all() as {
      puzzle: string;
      solution: string;
    }[];
    const row = rows.find((r) => JSON.stringify(JSON.parse(r.puzzle)) === JSON.stringify(puzzle));
    if (!row) throw new Error('the daily on the page is not in the database');
    return JSON.parse(row.solution) as number[];
  } finally {
    db.close();
  }
}

const penalty = (page: Page) => page.getByText(/^\+\d+s$/).first();

/** Presses start on the cover and waits for the puzzle. Today's is generated by the first start. */
export async function startDaily(page: Page) {
  // The big boards of the weekend take their time, to generate and to solve
  test.slow();
  await expect(page.getByRole('heading', { name: "Today's bridge" })).toBeVisible();
  await page.getByRole('button', { name: /^Start/ }).click();
  // An Oni (Sundays) takes the generator a few seconds. The first board is the daily's once it's
  // there to play: before, it's the empty one behind the cover, or one of the tips below the
  // daily while a new guest's daily loads again
  await expect(board(page)).toHaveClass(/board-interactive/, { timeout: 30_000 });
  await expect(board(page).locator('g.island').first()).toBeVisible();
  await expect(penalty(page)).toHaveText('+0s');
  const { puzzle } = await saved(page, DAILY_KEY);
  return { puzzle, solution: dailySolution(puzzle) };
}

/**
 * Solves the started daily: the first bridge by hand, a check (+10 s) and a hint (+30 s), then
 * hints for all but the last bridges, which are built by hand again. Hints keep it quick on the
 * big boards, the server only ranks results that took as long as the bridges the player built
 * need (`verify_log` in src/model/moves.rs), and a handful of clicks always does.
 */
export async function solveDaily(page: Page, puzzle: Puzzle, solution: number[]) {
  const first = solution.findIndex((b) => b > 0);
  await addBridge(page, DAILY_KEY, puzzle, first);

  await page.getByRole('button', { name: /^Check/ }).click();
  await expect(page.getByText('So far so good: every bridge belongs to the solution.')).toBeVisible();
  await expect(penalty(page)).toHaveText('+10s');

  const hint = page.getByRole('button', { name: /^Hint/ });
  const hintOnce = async () => {
    const before = JSON.stringify((await saved(page, DAILY_KEY)).bridges);
    await hint.click();
    // Polled often: a Sunday's Oni takes a hundred hints and more
    await expect
      .poll(async () => JSON.stringify((await saved(page, DAILY_KEY)).bridges), { intervals: [20, 50, 100] })
      .not.toBe(before);
  };
  await hintOnce();
  await expect(penalty(page)).toHaveText('+40s');
  while (missing((await saved(page, DAILY_KEY)).bridges, solution).length > 1) await hintOnce();

  const [last] = missing((await saved(page, DAILY_KEY)).bridges, solution);
  const built = (await saved(page, DAILY_KEY)).bridges[last];
  for (let n = built; n < solution[last]; n++) await addBridge(page, DAILY_KEY, puzzle, last);
}

/** The result card after the finish. */
export async function expectResult(page: Page) {
  const card = page.locator('aside > div').filter({ has: page.getByRole('heading', { name: /Well done!/ }) });
  await expect(card).toBeVisible();
  // The penalties are in the time: at least 40 s, in m:ss.d below ten minutes, h:mm:ss above
  await expect(card.locator('p.font-pixel.text-3xl')).toHaveText(/^(\d+:\d{2}\.\d|\d+:\d{2}(:\d{2})?)$/);
  await expect(card.getByText(/^Rank \d+ of \d+ today$/)).toBeVisible();
  await expect(card.getByText('Not on today\'s leaderboard')).toHaveCount(0);
  return card;
}

/**
 * Takes a player's daily results off the boards again: what a test that played changed for the
 * next one, or for its own retry.
 */
export function deleteResults(username: string) {
  const db = database();
  try {
    db.prepare('DELETE FROM attempts WHERE user_id IN (SELECT id FROM users WHERE username = ?)').run(username);
  } finally {
    db.close();
  }
}
