/// Applies the saved (or system) colour scheme before the first paint, so night mode doesn't flash.
const THEME_SCRIPT: &str = "try{var t=localStorage.getItem('hashi.theme');if(t==='dark'||(!t&&matchMedia('(prefers-color-scheme: dark)').matches))document.documentElement.classList.add('dark')}catch(e){}";

pub fn shell(options: LeptosOptions) -> impl IntoView {
    view! {
        <!DOCTYPE html>
        <html>
            <head>
                <meta charset="utf-8" />
                <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
                <meta name="author" content="Noel Huibers" />
                <meta name="color-scheme" content="light dark" />
                // The build of this page's WASM, for the tab to compare with the server's
                // (`api::client`)
                <meta name="hashi-build" content=page_build(&options) />
                <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
                <link rel="icon" href="/favicon.ico" sizes="32x32" />
                <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
                <link rel="manifest" href="/manifest.webmanifest" />
                <script inner_html=THEME_SCRIPT></script>
                // Self-hosted, generated by scripts/fonts.mjs
                <link rel="stylesheet" href="/fonts/fonts.css" />
                // Rendered here and not in <App/>: the hashed file name is only known on the server
                <HashedStylesheet options=options.clone() id="leptos" />
                <AutoReload options=options.clone() />
                <HydrationScripts options />
                <MetaTags />
            </head>
            <body>
                <App />
            </body>
        </html>
    }
}

/// See `server::build_id`.
#[cfg(feature = "ssr")]
fn page_build(options: &LeptosOptions) -> Option<String> {
    crate::server::build_id(options)
}

/// The shell is only rendered on the server.
#[cfg(not(feature = "ssr"))]
fn page_build(_: &LeptosOptions) -> Option<String> {
    None
}

#[component]
pub fn App() -> impl IntoView {
    provide_meta_context();
    provide_state();
    #[cfg(feature = "ssr")]
    provide_server_i18n();

    view! {
        // Sets <html lang dir>, remembers the language in a cookie, reads Accept-Language on the server
        <I18nContextProvider>
        // Title, description and social tags are set per page, see seo::PageMeta
        <Meta name="theme-color" content="#cf3a24" />

        <Router>
            <LocaleFromPath />
            <div class="flex min-h-screen flex-col pb-[calc(3.5rem+env(safe-area-inset-bottom))] md:pb-0">
                <Header />
                <main class="flex-1">
                    <Routes fallback=|| view! { <NotFound /> }>
                        // Every page in every language: /rules, /de/rules, /ja/rules, ...
                        <I18nRoute<Locale, _, _> view=Localized>
                            <Route path=path!("") view=DailyPage />
                            <Route path=path!("/practice") view=PlayPage />
                            <Route path=path!("/ranks") view=RanksPage />
                            <Route path=path!("/player/:id") view=PlayerPage />
                            <Route path=path!("/account") view=AccountPage />
                            <Route path=path!("/create") view=CreatePage />
                            <Route path=path!("/lab") view=LabPage />
                            <Route path=path!("/dojo") view=DojoPage />
                            <Route path=path!("/admin") view=AdminPage />
                            <Route path=path!("/dojo/seasons") view=DojoSeasonsPage />
                            <Route path=path!("/dojo/:id") view=DojoSubmissionPage />
                            <Route path=path!("/rules") view=RulesPage />
                            <Route path=path!("/impressum") view=ImpressumPage />
                            <Route path=path!("/datenschutz") view=PrivacyPage />
                            <Route path=path!("/kontakt") view=ContactPage />
                        </I18nRoute<Locale, _, _>>
                    </Routes>
                </main>
                <Footer />
            </div>
            <MobileNav />
            <Toaster />
            <Tooltips />
        </Router>
        </I18nContextProvider>
    }
}

/// The language context of a page on the server, made here instead of by `<I18nContextProvider>`
/// (which uses a context that is there already, and makes the same one otherwise).
///
/// `leptos_i18n` 0.6.2 (`init_context_inner`) starts an `Effect::new_isomorphic` with it that
/// copies the language into the cookie signal. On the server that effect is a tokio task of its own,
/// and `reactive_graph` 0.2.16 doesn't stop it when the page's owner is cleaned up at the end of
/// the response: on another worker thread it could run just then, read the language signal
/// that was dropped with `.get()` and panic ("Tried to access a reactive value that has
/// already been disposed", a few percent of all pages). Upstream fixed the same race for
/// `AsyncDerived` only (leptos-rs/leptos#4948, #4951, not released yet), not for effects.
///
/// So the owner of the context is paused right after making it: a paused effect skips its runs.
/// The cookie it set on the server only reached the response when the task happened to run
/// before the headers went out; the browser makes a context of its own, whose effect writes the
/// cookie. Pausing after making it, not before, keeps the cookie's first run, which repeats the
/// cookie the browser sent in the response.
#[cfg(feature = "ssr")]
fn provide_server_i18n() {
    let owner = Owner::new();
    let i18n = owner.with(leptos_i18n::context::init_i18n_context::<Locale>);
    owner.pause();
    provide_context(i18n);
    // The context's signals live as long as its owner: as long as the page
    on_cleanup(move || drop(owner));
}

/// The pages of a language. On the server only the route knows the language of the URL; above it
/// the language is the browser's (cookie or Accept-Language) until `LocaleFromPath` sets it,
/// while the browser starts with the URL's. Whatever renders elements depending on the language
/// goes in here, or the server leaves them out and hydration fails (it did for the script fonts).
#[component]
fn Localized() -> impl IntoView {
    view! {
        <ScriptFont />
        <Outlet />
    }
}

/// The header renders before `<I18nRoute>` takes the language from the URL. On the server it would
/// otherwise follow the cookie or Accept-Language, so a first visit to /ja/rules from an English
/// browser got an English header until hydration.
#[component]
fn LocaleFromPath() -> impl IntoView {
    let i18n = use_i18n();
    let path = leptos_router::hooks::use_location()
        .pathname
        .get_untracked();
    if let Some(locale) = crate::lang::path_locale(&path)
        && locale != i18n.get_locale_untracked()
    {
        i18n.set_locale(locale);
    }
}

/// Korean, Chinese, Arabic, Hindi, Thai and Vietnamese need a font for their script, loaded only
/// for them.
#[component]
fn ScriptFont() -> impl IntoView {
    let i18n = use_i18n();
    move || {
        script_font(i18n.get_locale()).map(|sheet| {
            // Through leptos_meta, a <link> in the body breaks hydration
            view! { <Link rel="stylesheet" href=format!("/fonts/{sheet}.css") /> }
        })
    }
}
