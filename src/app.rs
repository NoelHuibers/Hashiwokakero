/// Applies the saved (or system) colour scheme before the first paint, so night mode doesn't flash.
const THEME_SCRIPT: &str = "try{var t=localStorage.getItem('hashi.theme');if(t==='dark'||(!t&&matchMedia('(prefers-color-scheme: dark)').matches))document.documentElement.classList.add('dark')}catch(e){}";

pub fn shell(options: LeptosOptions) -> impl IntoView {
    view! {
        <!DOCTYPE html>
        <html>
            <head>
                <meta charset="utf-8" />
                <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
                <meta name="author" content="Noel Huibers" />
                <meta name="color-scheme" content="light dark" />
                <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
                <link rel="icon" href="/favicon.ico" sizes="32x32" />
                <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
                <link rel="manifest" href="/manifest.webmanifest" />
                <script inner_html=THEME_SCRIPT></script>
                // Self-hosted, generated by scripts/fonts.mjs
                <link rel="stylesheet" href="/fonts/fonts.css" />
                // Rendered here and not in <App/>: the hashed file name is only known on the server
                <HashedStylesheet options=options.clone() id="leptos" />
                <AutoReload options=options.clone() />
                <HydrationScripts options />
                <MetaTags />
            </head>
            <body>
                <App />
            </body>
        </html>
    }
}

#[component]
pub fn App() -> impl IntoView {
    provide_meta_context();
    provide_state();

    view! {
        // Sets <html lang dir>, remembers the language in a cookie, reads Accept-Language on the server
        <I18nContextProvider>
        // Title, description and social tags are set per page, see seo::PageMeta
        <Meta name="theme-color" content="#cf3a24" />
        <ScriptFont />

        <Router>
            <div class="flex min-h-screen flex-col pb-[calc(3.5rem+env(safe-area-inset-bottom))] md:pb-0">
                <Header />
                <main class="flex-1">
                    <Routes fallback=|| view! { <NotFound /> }>
                        // Every page in every language: /rules, /de/rules, /ja/rules, ...
                        <I18nRoute<Locale, _, _> view=Outlet>
                            <Route path=path!("") view=DailyPage />
                            <Route path=path!("/practice") view=PlayPage />
                            <Route path=path!("/ranks") view=RanksPage />
                            <Route path=path!("/account") view=AccountPage />
                            <Route path=path!("/create") view=CreatePage />
                            <Route path=path!("/lab") view=LabPage />
                            <Route path=path!("/dojo") view=DojoPage />
                            <Route path=path!("/admin") view=AdminPage />
                            <Route path=path!("/dojo/:id") view=DojoSubmissionPage />
                            <Route path=path!("/rules") view=RulesPage />
                            <Route path=path!("/impressum") view=ImpressumPage />
                            <Route path=path!("/datenschutz") view=PrivacyPage />
                        </I18nRoute<Locale, _, _>>
                    </Routes>
                </main>
                <Footer />
            </div>
            <MobileNav />
            <Toaster />
        </Router>
        </I18nContextProvider>
    }
}

/// Korean, Chinese, Arabic, Hindi, Thai and Vietnamese need a font for their script, loaded only
/// for them.
#[component]
fn ScriptFont() -> impl IntoView {
    let i18n = use_i18n();
    move || {
        script_font(i18n.get_locale()).map(|sheet| {
            // Through leptos_meta, a <link> in the body breaks hydration
            view! { <Link rel="stylesheet" href=format!("/fonts/{sheet}.css") /> }
        })
    }
}
