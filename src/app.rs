/// The language context of a page on the server, made here instead of by `<I18nContextProvider>`
/// (which uses a context that is there already, and makes the same one otherwise).
///
/// `leptos_i18n` 0.6.2 (`init_context_inner`) starts an `Effect::new_isomorphic` with it that
/// copies the language into the cookie signal. On the server that effect is a tokio task of its own,
/// and `reactive_graph` 0.2.16 doesn't stop it when the page's owner is cleaned up at the end of
/// the response: on another worker thread it could run just then, read the language signal
/// that was dropped with `.get()` and panic ("Tried to access a reactive value that has
/// already been disposed", a few percent of all pages). Upstream fixed the same race for
/// `AsyncDerived` only (leptos-rs/leptos#4948, #4951, not released yet), not for effects.
///
/// So the owner of the context is paused right after making it: a paused effect skips its runs.
/// The cookie it set on the server only reached the response when the task happened to run
/// before the headers went out; the browser makes a context of its own, whose effect writes the
/// cookie. Pausing after making it, not before, keeps the cookie's first run, which repeats the
/// cookie the browser sent in the response.
#[cfg(feature = "ssr")]
pub(crate) fn provide_server_i18n() {
    let owner = Owner::new();
    let i18n = owner.with(leptos_i18n::context::init_i18n_context::<Locale>);
    owner.pause();
    provide_context(i18n);
    // The context's signals live as long as its owner: as long as the page
    on_cleanup(move || drop(owner));
}

/// The pages of a language. On the server only the route knows the language of the URL; above it
/// the language is the browser's (cookie or Accept-Language) until `LocaleFromPath` sets it,
/// while the browser starts with the URL's. Whatever renders elements depending on the language
/// goes in here, or the server leaves them out and hydration fails (it did for the script fonts).
#[component]
fn Localized() -> impl IntoView {
    view! {
        <ScriptFont />
        <Outlet />
    }
}

/// The header renders before `<I18nRoute>` takes the language from the URL. On the server it would
/// otherwise follow the cookie or Accept-Language, so a first visit to /ja/rules from an English
/// browser got an English header until hydration.
#[component]
fn LocaleFromPath() -> impl IntoView {
    let i18n = use_i18n();
    let path = leptos_router::hooks::use_location()
        .pathname
        .get_untracked();
    if let Some(locale) = crate::lang::path_locale(&path)
        && locale != i18n.get_locale_untracked()
    {
        i18n.set_locale(locale);
    }
}

/// The old address of a page that moved (`seo::MOVED_PAGES`): goes on to the new one with the
/// query and fragment, in place of the old one in the history. The server redirects these
/// itself before any page renders; this is for the app, whose pages have no server in front of
/// them (an App Link to `/practice`, a link of a page cached from before), and for client-side
/// navigation. A path the route matches but no page moved from (`/dojo/abc`, no entry's number)
/// is not found.
///
/// After the navigation to the old address is done, in the next frame: the router adds that one
/// to the history only once its page rendered, so a redirect while it renders replaced the page
/// before it instead (back skipped it).
#[component]
fn MovedPage() -> impl IntoView {
    let location = leptos_router::hooks::use_location();
    let target = moved_target(
        &location.pathname.get_untracked(),
        &location.search.get_untracked(),
        &location.hash.get_untracked(),
    );
    let Some(target) = target else {
        return view! { <NotFound /> }.into_any();
    };
    #[cfg(feature = "browser")]
    {
        let navigate = leptos_router::hooks::use_navigate();
        request_animation_frame(move || {
            let options = leptos_router::NavigateOptions {
                replace: true,
                ..Default::default()
            };
            navigate(&target, options);
        });
    }
    #[cfg(not(feature = "browser"))]
    drop(target);
    ().into_any()
}

/// Where [`MovedPage`] at `path` leads, with the `search` and `hash` of its URL (with or without
/// their `?` and `#`).
fn moved_target(path: &str, search: &str, hash: &str) -> Option<String> {
    let mut target = crate::seo::moved_page(path)?;
    let search = search.trim_start_matches('?');
    if !search.is_empty() {
        target = format!("{target}?{search}");
    }
    let hash = hash.trim_start_matches('#');
    if !hash.is_empty() {
        target = format!("{target}#{hash}");
    }
    Some(target)
}

/// In the app: the pages of the App Links it is opened with (`api::native::follow_app_links`).
/// Nothing on the website, where the browser opens them itself.
#[component]
fn AppLinks() -> impl IntoView {
    #[cfg(feature = "csr")]
    crate::api::native::follow_app_links(leptos_router::hooks::use_navigate());
}

/// Korean, Chinese, Arabic, Hindi, Thai and Vietnamese need a font for their script, loaded only
/// for them.
#[component]
fn ScriptFont() -> impl IntoView {
    let i18n = use_i18n();
    move || {
        script_font(i18n.get_locale()).map(|sheet| {
            // Through leptos_meta, a <link> in the body breaks hydration
            view! { <Link rel="stylesheet" href=format!("/fonts/{sheet}.css") /> }
        })
    }
}

#[cfg(test)]
mod tests {
    /// The app's router takes an old address to the new one with its query and fragment.
    #[test]
    fn moved_pages_keep_the_query() {
        use super::moved_target;
        assert_eq!(moved_target("/practice", "", "").as_deref(), Some("/play"));
        assert_eq!(
            moved_target("/de/practice", "?size=9", "").as_deref(),
            Some("/de/play?size=9")
        );
        assert_eq!(
            moved_target("/ja/practice", "size=9&x=1", "#board").as_deref(),
            Some("/ja/play?size=9&x=1#board")
        );
        assert_eq!(moved_target("/play", "?size=9", ""), None);
        // The Dojo's pages, the Lab's tabs now
        assert_eq!(
            moved_target("/dojo", "?budget=4", "#leaderboard").as_deref(),
            Some("/lab/leaderboard?budget=4#leaderboard")
        );
        assert_eq!(
            moved_target("/ja/dojo/seasons", "", "#season-3").as_deref(),
            Some("/ja/lab/seasons#season-3")
        );
        assert_eq!(
            moved_target("/de/dojo/benchmarks", "?submitted=3", "#mine").as_deref(),
            Some("/de/lab/benchmarks?submitted=3#mine")
        );
        assert_eq!(
            moved_target("/dojo/12", "", "").as_deref(),
            Some("/lab/solver/12")
        );
        assert_eq!(moved_target("/dojo/abc", "", ""), None);
    }

    /// The mobile app's page (app/index.html, see app/README.md) applies the theme with a copy of
    /// the same script. The app's content security policy allows inline scripts by their hash,
    /// so the copy must stay identical, and be the page's only inline script.
    #[test]
    fn app_page_has_the_theme_script() {
        let page = include_str!("../app/index.html");
        assert!(
            page.contains(&format!("<script>{}</script>", super::THEME_SCRIPT)),
            "app/index.html must have THEME_SCRIPT as it is"
        );
        assert_eq!(page.matches("<script").count(), 1, "app/index.html");
    }
}
