#![recursion_limit = "256"]

#[cfg(feature = "ssr")]
#[tokio::main]
async fn main() {
    use leptos::prelude::*;

    if let Err(e) = hashi::server::db::init().await {
        eprintln!("{e}");
        std::process::exit(1);
    }
    hashi::server::dojo::start_dispatcher();
    hashi::server::daily::start_stamp_sync();
    hashi::server::auth::start_cleanup();

    // Reads the cargo-leptos settings (Cargo.toml) or the LEPTOS_* environment variables
    let conf = get_configuration(None).expect("invalid Leptos configuration");
    let leptos_options = conf.leptos_options;
    let addr = leptos_options.site_addr;
    // Generated by scripts/fonts.mjs, without them the site silently falls back to system fonts
    if !std::path::Path::new(&*leptos_options.site_root)
        .join("fonts/fonts.css")
        .exists()
    {
        eprintln!(
            "warning: the fonts are missing, run `pnpm install` (or `pnpm run fonts`) and rebuild"
        );
    }

    // The routes live in the library (server/router), where the tests drive them
    let app = hashi::server::router(leptos_options, hashi::app::shell);

    let listener = tokio::net::TcpListener::bind(&addr)
        .await
        .expect("could not bind the server address");
    println!("listening on http://{addr}");
    axum::serve(listener, app.into_make_service())
        .with_graceful_shutdown(shutdown_signal())
        .await
        .expect("server error");
}

/// fly.io stops machines with SIGINT/SIGTERM, which a container's PID 1 ignores by default.
#[cfg(feature = "ssr")]
async fn shutdown_signal() {
    use tokio::signal::unix::{SignalKind, signal};
    let mut terminate = signal(SignalKind::terminate()).expect("could not listen for SIGTERM");
    tokio::select! {
        _ = tokio::signal::ctrl_c() => {}
        _ = terminate.recv() => {}
    }
}

